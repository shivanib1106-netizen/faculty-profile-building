import React, { useCallback, useEffect, useState } from 'react';
import Layout from '../components/Layout';
import Loading from '../components/Loading';
import ErrorMessage from '../components/ErrorMessage';
import EmptyState from '../components/EmptyState';
import StatusBadge from '../components/StatusBadge';
import Icon from '../components/Icon';
import useAuth from '../hooks/useAuth';
import { reportApi } from '../api/reportApi';
import { hodApi } from '../api/hodApi';
import { triggerDownload } from '../api/apiClient';
import { useAcademicYears } from '../hooks/useReferenceData';
import { formatDate } from '../utils/helpers';

const REPORT_TYPES = {
  faculty: [
    { id: 'faculty-api', label: 'Faculty API report', description: 'Category-wise API score and verification summary.' },
    { id: 'academic-year', label: 'Academic-year report', description: 'All submitted activities for the selected year.' },
    { id: 'category-wise', label: 'Category-wise report', description: 'Breakdown of activities by Category I, II and III.' },
    { id: 'activity-wise', label: 'Activity-wise report', description: 'Detailed list of every activity with status.' },
    { id: 'verification', label: 'Verification report', description: 'Approved, pending and rejected activities with remarks.' },
  ],
  hod: [
    { id: 'department-summary', label: 'Department summary', description: 'Faculty count and department activity overview.' },
    { id: 'faculty-api', label: 'Faculty API report', description: 'API scores across all faculty in your department.' },
    { id: 'verification', label: 'Verification report', description: 'Department verification outcomes and pending items.' },
  ],
  admin: [
    { id: 'institution-summary', label: 'Institution summary', description: 'Users, departments and activity totals.' },
    { id: 'faculty-api', label: 'Faculty API report', description: 'Institution-wide faculty API scores.' },
    { id: 'category-wise', label: 'Category-wise report', description: 'Activity distribution across categories.' },
    { id: 'verification', label: 'Verification report', description: 'Pending and completed verifications across departments.' },
  ],
};

const PAGE_TITLE = {
  faculty: 'Reports',
  hod: 'Department Reports',
  admin: 'Reports',
};

export const Reports = () => {
  const { user } = useAuth();
  const role = user?.role || 'faculty';
  const types = REPORT_TYPES[role] || REPORT_TYPES.faculty;
  const { years, activeYear } = useAcademicYears();

  const [reportType, setReportType] = useState(types[0].id);
  const [year, setYear] = useState('');
  const [preview, setPreview] = useState(null);
  const [loading, setLoading] = useState(false);
  const [downloading, setDownloading] = useState(false);
  const [error, setError] = useState('');
  const [success, setSuccess] = useState('');

  useEffect(() => {
    if (!year && activeYear) setYear(activeYear);
  }, [activeYear, year]);

  const loadPreview = useCallback(async () => {
    if (!year) {
      setError('Select an academic year first.');
      return;
    }
    setLoading(true);
    setError('');
    setSuccess('');
    setPreview(null);
    try {
      let data;
      if (role === 'hod') {
        data = await hodApi.getDepartmentReports(reportType, year);
      } else if (role === 'admin') {
        data = await reportApi.getInstitutionReportPreview(reportType, year);
      } else {
        data = await reportApi.getReportPreview(reportType, year);
      }
      setPreview(data);
    } catch (err) {
      setError(
        err.status === 404
          ? 'No report is available for this type and academic year yet.'
          : err.message || 'The report preview could not be generated.'
      );
    } finally {
      setLoading(false);
    }
  }, [reportType, role, year]);

  const downloadPdf = async () => {
    if (!year) {
      setError('Select an academic year first.');
      return;
    }
    setDownloading(true);
    setError('');
    setSuccess('');
    try {
      let blob;
      if (role === 'hod') {
        blob = await hodApi.downloadDepartmentReport(reportType, year);
      } else if (role === 'admin') {
        blob = await reportApi.downloadInstitutionReportPdf(reportType, year);
      } else {
        blob = await reportApi.downloadReportPdf(reportType, year);
      }
      triggerDownload(blob, `${reportType}_${year}.pdf`);
      setSuccess('The PDF was generated by the server and downloaded.');
    } catch (err) {
      setError(err.message || 'The PDF could not be generated.');
    } finally {
      setDownloading(false);
    }
  };

  const activeType = types.find((type) => type.id === reportType) || types[0];

  return (
    <Layout title={PAGE_TITLE[role] || 'Reports'}>
      <div className="page-header">
        <div className="page-header-title-group">
          <h1>{PAGE_TITLE[role] || 'Reports'}</h1>
          <p className="page-header-subtitle">
            PDF generation is performed by the Flask backend. Reports are downloaded, never assembled here.
          </p>
        </div>
      </div>

      {error && <ErrorMessage message={error} />}
      {success && (
        <div className="alert-box alert-box-success" role="status">
          <Icon name="checkCircle" size={16} /> {success}
        </div>
      )}

      <div className="reports-layout">
        <aside className="report-type-list">
          <h2 className="report-type-list-title">Report type</h2>
          {types.map((type) => (
            <button
              key={type.id}
              type="button"
              className={`report-type-button ${reportType === type.id ? 'active' : ''}`}
              onClick={() => {
                setReportType(type.id);
                setPreview(null);
                setError('');
                setSuccess('');
              }}
            >
              <Icon name="file" size={16} />
              <span>
                <span className="report-type-name">{type.label}</span>
                <span className="report-type-desc">{type.description}</span>
              </span>
            </button>
          ))}
        </aside>

        <section className="report-panel">
          <div className="report-panel-toolbar">
            <div className="form-group form-group-inline">
              <label className="form-label" htmlFor="report-year">Academic year</label>
              <select
                id="report-year"
                className="filter-select"
                value={year}
                onChange={(event) => {
                  setYear(event.target.value);
                  setPreview(null);
                  setSuccess('');
                }}
              >
                <option value="">Select year</option>
                {years.map((item) => (
                  <option key={item.id || item.year} value={item.year}>
                    {item.year}{item.status === 'Active' ? ' (Active)' : ''}
                  </option>
                ))}
              </select>
            </div>
            <div className="report-panel-actions">
              <button type="button" className="btn btn-secondary" onClick={loadPreview} disabled={loading || !year}>
                <Icon name="eye" size={15} /> {loading ? 'Loading...' : 'Preview'}
              </button>
              <button type="button" className="btn btn-primary" onClick={downloadPdf} disabled={downloading || !year}>
                <Icon name="download" size={15} /> {downloading ? 'Generating...' : 'Download PDF'}
              </button>
            </div>
          </div>

          <div className="report-panel-selection">
            <h2>{activeType.label}</h2>
            <p>{activeType.description}</p>
          </div>

          {loading ? (
            <Loading message="Requesting report preview from the server..." />
          ) : !preview ? (
            <EmptyState
              icon="file"
              title="No preview loaded"
              description="Choose an academic year and select Preview to fetch report details from the server."
            />
          ) : (
            <div className="report-preview">
              <div className="report-preview-head">
                <div>
                  <h3>{preview.institution || 'Institution'}</h3>
                  <p>
                    {preview.reportType || reportType} &bull; {preview.academicYear || year}
                  </p>
                </div>
                <StatusBadge status={preview.status || 'Generated'} />
              </div>

              <dl className="report-meta-grid">
                {preview.facultyName && (
                  <div><dt>Faculty</dt><dd>{preview.facultyName}</dd></div>
                )}
                {preview.employeeId && (
                  <div><dt>Employee ID</dt><dd>{preview.employeeId}</dd></div>
                )}
                {preview.department && (
                  <div><dt>Department</dt><dd>{preview.department}</dd></div>
                )}
                {preview.facultyCount !== undefined && (
                  <div><dt>Faculty members</dt><dd>{preview.facultyCount}</dd></div>
                )}
                {preview.scope && (
                  <div><dt>Scope</dt><dd>{preview.scope}</dd></div>
                )}
                <div>
                  <dt>Generated</dt>
                  <dd>{preview.generatedAt ? formatDate(preview.generatedAt) : 'Not provided'}</dd>
                </div>
              </dl>

              {(preview.category1Score !== undefined || preview.totalScore !== undefined) && (
                <div className="report-score-grid">
                  <div>
                    <span>Category I</span>
                    <strong>{preview.category1Score ?? '—'}</strong>
                  </div>
                  <div>
                    <span>Category II</span>
                    <strong>{preview.category2Score ?? '—'}</strong>
                  </div>
                  <div>
                    <span>Category III</span>
                    <strong>{preview.category3Score ?? '—'}</strong>
                  </div>
                  <div className="report-score-total">
                    <span>Total</span>
                    <strong>{preview.totalScore ?? '—'}</strong>
                  </div>
                </div>
              )}

              {preview.institutionTotals && (
                <div className="report-score-grid">
                  <div><span>Faculty</span><strong>{preview.institutionTotals.faculty ?? '—'}</strong></div>
                  <div><span>Departments</span><strong>{preview.institutionTotals.departments ?? '—'}</strong></div>
                  <div><span>Activities</span><strong>{preview.institutionTotals.activities ?? '—'}</strong></div>
                </div>
              )}

              {preview.summaryNotes && (
                <div className="alert-box alert-box-info">{preview.summaryNotes}</div>
              )}

              <p className="report-generation-note">
                <Icon name="info" size={14} /> Downloading triggers server-side PDF generation. If the
                server has not published this report, you will receive a clear error instead of a file.
              </p>
            </div>
          )}
        </section>
      </div>
    </Layout>
  );
};

export default Reports;
